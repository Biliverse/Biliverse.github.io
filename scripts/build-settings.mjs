import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const repositories = path.resolve(root, "..");
const names = ["Enhanced", "Global", "Redirect", "ADBlock"];
const source = path.join(root, "settings");
const check = process.argv.includes("--check");
const read = name => readFile(path.join(source, name), "utf8");
const site = JSON.parse(await read("site.boxjs.json"));
const modules = [];
const schemas = {};
const outputs = new Map();
async function themedIcon(directory, prefix) {
  const variants = {};
  for (const mode of ["light", "dark"]) {
    const filename = `${prefix}_settings_${mode}.png`;
    const png = await readFile(path.join(directory, filename));
    variants[mode] = `data:image/png;base64,${png.toString("base64")}`;
  }
  return variants;
}
for (const name of names) {
  const repo = path.join(repositories, name);
  const argsFull = name === "Enhanced" ? [] : (await import(pathToFileURL(path.join(repo, "arguments-builder.full.config.ts")))).argsFull;
  schemas[name] = argsFull.map(({ key, name, type, defaultValue, description, options }) => ({
    key, name, type, defaultValue: type === "number" ? Number(defaultValue) : defaultValue, description,
    ...(options ? { options: options.map(({ key, label }) => ({ key: type === "number" ? Number(key) : key, label })) } : {}),
  }));
  if (name !== "Enhanced" && !schemas[name].some(field => field.key === "Storage")) schemas[name].push({ key: "Storage", name: "[储存] 配置类型", type: "string", defaultValue: "Argument", description: "选择模块参数、持久化设置或默认配置。", options: [{ key: "Argument", label: "模块参数" }, { key: "PersistentStore", label: "本地设置" }, { key: "database", label: "默认配置" }] });
  const description = name === "Enhanced" ? site.apps.find(app => app.module === name).desc : JSON.parse(await readFile(path.join(repo, "package.json"), "utf8")).description.split("\n").at(-1);
  const iconDirectory = name === "Enhanced" ? path.join(source, "icons") : path.join(repo, "src/assets");
  const iconPrefix = name === "Enhanced" ? name : "icon";
  const icon = await themedIcon(iconDirectory, iconPrefix);
  for (const mode of ["light", "dark"])
    outputs.set(path.join(root, `docs/public/settings/assets/${name}_${mode}.png`), await readFile(path.join(iconDirectory, `${iconPrefix}_settings_${mode}.png`)));
  modules.push({ name, description, icon });
}
const logo = await themedIcon(source, "logo");
const js = (await read("app.js")).replace("/* MODULES */", JSON.stringify(modules)).replace("/* LOGO */", JSON.stringify(logo));
const html = (await read("index.html")).replace("/* FORM_CSS */", await read("bilibili-form.css")).replace("/* APP_CSS */", await read("app.css")).replace("/* SELF_SERVICE_CSS */", await read("bilibili-self-service.css")).replace("/* APP_JS */", js);
outputs.set(path.join(root, "docs/public/settings/index.html"), html);
outputs.set(path.join(root, "docs/public/settings/logo.png"), await readFile(path.join(source, "logo.png")));
for (const mode of ["light", "dark"]) {
  const filename = `logo_settings_${mode}.png`;
  outputs.set(path.join(root, "docs/public/settings", filename), await readFile(path.join(source, filename)));
}
for (const name of names) {
  if (name === "Enhanced") continue; // Enhanced supplies JSON; the package supplies its page and runtime.
  const moduleHtml = html;
  outputs.set(path.join(root, `docs/public/settings/assets/${name}.html`), moduleHtml);
  outputs.set(path.join(root, `docs/public/settings/${name}/index.html`), moduleHtml);
  const generated = `// Generated by Biliverse.github.io/scripts/build-settings.mjs. Do not edit.\nconst MODULE = ${JSON.stringify(name)};\nconst fields = ${JSON.stringify(schemas[name])};\n\n${await read("handler.mjs")}`;
  outputs.set(path.join(repositories, name, "src/function/settings.mjs"), generated);
}
for (const name of ["index.html", "app.mjs", "panel.css", "home.css"])
  outputs.set(path.join(root, "docs/public/settings/assets", name), await readFile(fileURLToPath(import.meta.resolve(`@nsnanocat/preference-panes/dist/settings/${name}`))));
outputs.set(path.join(root, "docs/public/settings/assets/site.boxjs.json"), await readFile(path.join(source, "site.boxjs.json")));
const proxyRuntime = await readFile(fileURLToPath(import.meta.resolve("@nsnanocat/preference-panes/dist/preference-panes.proxy.js")), "utf8");
outputs.set(path.join(root, "docs/public/settings/assets/PreferencePanes.request.js"), `${proxyRuntime}\nPreferencePanes.runPreferences(${JSON.stringify(JSON.parse(await read("proxies.json")))});\n`);
const boxjs = await readFile(path.join(repositories, "Enhanced/template/boxjs.settings.json"), "utf8");
outputs.set(path.join(root, "docs/public/settings/assets/Enhanced.boxjs.json"), boxjs);
const configRuntime = await readFile(fileURLToPath(import.meta.resolve("@nsnanocat/preference-panes/dist/preference-panes.config.js")), "utf8");
outputs.set(path.join(root, "docs/public/settings/assets/Enhanced.config.js"), `${configRuntime}\nPreferencePanes.mockConfiguration(${JSON.stringify(JSON.parse(boxjs))});\n`);
for (const extension of ["sgmodule", "plugin", "snippet", "stoverride", "conf"])
  outputs.set(path.join(root, `docs/public/settings/PreferencePanes.${extension}`), await readFile(path.join(source, `PreferencePanes.${extension}`)));
const enhancedPage = outputs.get(path.join(root, "docs/public/settings/assets/index.html"));
outputs.set(path.join(root, "docs/public/settings/index.html"), enhancedPage);
for (const { module } of site.apps) {
  outputs.set(path.join(root, `docs/public/settings/${module}/index.html`), enhancedPage);
  outputs.set(path.join(root, `docs/public/settings/assets/${module}.html`), enhancedPage);
}
for (const [filename, text] of outputs) {
  if (check) {
    if (!(await readFile(filename)).equals(Buffer.from(text))) throw new Error(`Settings generated file is stale: ${filename}`);
  } else { await mkdir(path.dirname(filename), { recursive: true }); await writeFile(filename, text); }
}
console.log(JSON.stringify({ legacyModules: names.filter(name => name !== "Enhanced").map(name => ({ name, options: schemas[name].length })), outputs: outputs.size, check }, null, 2));
